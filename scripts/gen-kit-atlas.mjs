// Codegen: emits native/renderer/generated/kit_atlas.h — the kit's one colour
// atlas (public/assets/toycar/Textures/colormap.png) as RGB bytes, so the
// renderer can colour a baked copy's vertices at scene build without decoding
// a PNG or reading a texture back. ttp/kit_colors.h samples it and says why a
// vertex sample is exact. Gated by tests/codegen-freshness.test.js.
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'public/assets/toycar/Textures/colormap.png');
const OUT = path.join(ROOT, 'native/renderer/generated/kit_atlas.h');

// The smallest PNG reader that covers the kit's atlases: 8-bit RGB, RGBA or
// palette, non-interlaced. Anything else is refused loudly.
const readPng = (file) => {
  const buf = fs.readFileSync(file);
  if (buf.readUInt32BE(0) !== 0x89504e47) throw new Error(`${file}: not a PNG`);
  let pos = 8, width = 0, height = 0, channels = 0, palette = null;
  const idat = [];
  while (pos < buf.length) {
    const len = buf.readUInt32BE(pos), type = buf.toString('ascii', pos + 4, pos + 8);
    const data = buf.subarray(pos + 8, pos + 8 + len);
    if (type === 'IHDR') {
      width = data.readUInt32BE(0); height = data.readUInt32BE(4);
      const depth = data[8], color = data[9], interlace = data[12];
      channels = { 2: 3, 3: 1, 6: 4 }[color];
      if (depth !== 8 || !channels || interlace) throw new Error(`${file}: unsupported PNG (${depth}-bit, colour ${color}, interlace ${interlace})`);
    } else if (type === 'PLTE') palette = Buffer.from(data);
    else if (type === 'IDAT') idat.push(data);
    pos += 12 + len;
  }
  const raw = zlib.inflateSync(Buffer.concat(idat));
  const stride = width * channels, out = Buffer.alloc(height * stride);
  const paeth = (a, b, c) => { const p = a + b - c, pa = Math.abs(p - a), pb = Math.abs(p - b), pc = Math.abs(p - c); return pa <= pb && pa <= pc ? a : pb <= pc ? b : c; };
  for (let y = 0; y < height; y++) {
    const filter = raw[y * (stride + 1)], src = y * (stride + 1) + 1, dst = y * stride;
    for (let i = 0; i < stride; i++) {
      const x = raw[src + i];
      const a = i >= channels ? out[dst + i - channels] : 0;
      const b = y > 0 ? out[dst - stride + i] : 0;
      const c = y > 0 && i >= channels ? out[dst - stride + i - channels] : 0;
      out[dst + i] = (x + [0, a, b, (a + b) >> 1, paeth(a, b, c)][filter]) & 0xff;
    }
  }
  if (channels === 1) {
    if (!palette) throw new Error(`${file}: palette PNG without PLTE`);
    const rgb = Buffer.alloc(width * height * 3);
    for (let i = 0; i < width * height; i++) rgb.set(palette.subarray(out[i] * 3, out[i] * 3 + 3), i * 3);
    return { width, height, channels: 3, px: rgb };
  }
  return { width, height, channels, px: out };
};

const img = readPng(SRC);
const rgb = [];
for (let i = 0; i < img.width * img.height; i++) rgb.push(img.px[i * img.channels], img.px[i * img.channels + 1], img.px[i * img.channels + 2]);
const rows = [];
for (let i = 0; i < rgb.length; i += 48) rows.push('    ' + rgb.slice(i, i + 48).join(','));
const text = `// GENERATED by scripts/gen-kit-atlas.mjs from public/assets/toycar/Textures/colormap.png — do not edit.
// The kit's colour atlas as RGB bytes, top row first (ttp/kit_colors.h samples it).
#pragma once
#include <cstdint>

namespace ttp { namespace kitcolors {

inline constexpr int kAtlasWidth = ${img.width};
inline constexpr int kAtlasHeight = ${img.height};
inline const uint8_t kAtlas[] = {
${rows.join(',\n')}
};

}}  // namespace ttp::kitcolors
`;
// --stdout is the freshness gate's spelling (tests/codegen-freshness.test.js).
if (process.argv.includes('--stdout')) process.stdout.write(text);
else {
  fs.writeFileSync(OUT, text);
  console.log(`wrote ${path.relative(ROOT, OUT)}: ${img.width} x ${img.height}`);
}

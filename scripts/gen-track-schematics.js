'use strict';
// Generate the catalogue's top-down track maps, ONE bake written twice:
//
//   public/shared/trackSchematics.js            the full-res maps for the PHONE's
//     no-relay preview — a phone has no wasm to ask, so it reads them as data.
//   native/libttp-track/generated/track_maps.h  the same maps plus each one's
//     packed chooser form, compiled into the engine beside track_defs.h, so
//     ttp_track_schematic_json is a lookup and ttp_ui_chooser_tracks_json hands
//     every shell the phones' track list without building or simplifying a
//     track at boot.
//
// The projection is NATIVE (libttp-track's ttp::schematic, via
// scripts/native-track.mjs over the shipped wasm), driven by each track's
// DESCRIPTOR rather than its id: an id answers out of the bake this writes, a
// descriptor builds. So a re-laid track needs no wasm rebuild before this runs —
// only after, to compile the new header in. A change to the BUILDER or the
// projection is different: this would bake the old wasm's answer, so rebuild the
// wasm first, run this, then rebuild again.
//
// The JS twin it replaced (public/display/trackSchematic.js) was the oracle
// tests/fixtures/schematic-corpus.jsonl was recorded off, and was retired once
// that corpus had frozen its output — so the JS bytes below are still the ones
// the JS wrote, and the `schematic` ctest is what holds the native projection to
// them. The same ctest rebuilds every catalogue track against the header.
//
// Run after editing any track layout:  node scripts/gen-track-schematics.js
// (tests/track.test.js and the `schematic` ctest fail if either file drifts.)
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');

(async () => {
  const { init, trackSchematic, schematicPack } = await import('../scripts/native-track.mjs');
  await init();
  const { TRACK_LIST } = await import('../public/shared/tracks.js');
  const maps = TRACK_LIST.map((t) => ({ id: t.id, s: trackSchematic(t) }));

  const js =
    '// GENERATED by scripts/gen-track-schematics.js — DO NOT EDIT BY HAND.\n' +
    '// Real top-down track maps (precomputed from geometry) so dependency-free\n' +
    '// consumers can render actual schematics without building a track. Regenerate after\n' +
    '// editing a track: node scripts/gen-track-schematics.js (track.test.js guards it).\n' +
    `export const TRACK_SCHEMATICS = {\n${maps.map(({ id, s }) => `  ${id}: ${JSON.stringify(s)}`).join(',\n')}\n};\n`;

  // Numbers go across as JS's shortest round-trip spelling, which a C++ compiler
  // parses back to the same double (both round correctly), so no value moves.
  const row = ({ id, s }) => {
    if (!s.d || !s.start || !s.proj) throw new Error(`gen-track-schematics: "${id}" projected no map`);
    const { minX, minZ, scale, offX, offZ } = s.proj;
    return `  { ${JSON.stringify(id)}, ${JSON.stringify(s.d)},\n`
      + `    ${[s.start.x, s.start.y, minX, minZ, scale, offX, offZ].join(', ')},\n`
      + `    ${JSON.stringify(schematicPack(s.d))} },`;
  };
  const h = [
    '// GENERATED by scripts/gen-track-schematics.js — DO NOT EDIT BY HAND.',
    '// The catalogue\'s top-down maps (ttp::schematic::build of each shipped track) and',
    '// their packed chooser form (ttp::schematic::pack at EPS), baked so no shell',
    '// builds a track to draw one. The `schematic` ctest rebuilds every catalogue',
    '// track and demands these back. Regenerate: node scripts/gen-track-schematics.js',
    '#pragma once',
    '',
    '#include <string>',
    '',
    'namespace ttp {',
    '',
    'struct TrackMapDef {',
    '  const char* id;',
    '  const char* d;  // the full-resolution path',
    '  double startX, startY;',
    '  double minX, minZ, scale, offX, offZ;  // schematic::Projection',
    '  const char* packed;',
    '};',
    '',
    'inline constexpr TrackMapDef TTP_TRACK_MAPS[] = {',
    ...maps.map(row),
    '};',
    `inline constexpr int TTP_TRACK_MAP_COUNT = ${maps.length};`,
    '',
    '// Catalogue ids only: a dev track has no baked map.',
    'inline const TrackMapDef* find_track_map(const std::string& id) {',
    '  for (const TrackMapDef& m : TTP_TRACK_MAPS)',
    '    if (id == m.id) return &m;',
    '  return nullptr;',
    '}',
    '',
    '}  // namespace ttp',
    '',
  ].join('\n');

  for (const [rel, text] of [['public/shared/trackSchematics.js', js],
                             ['native/libttp-track/generated/track_maps.h', h]]) {
    fs.writeFileSync(path.join(ROOT, rel), text);
    console.log(`wrote ${rel} (${maps.length} tracks)`);
  }
})();

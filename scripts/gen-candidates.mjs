// Bake the AUDITION CANDIDATES into public/shared/candidateTracks.js — extra tracks
// (4 per cup section) shown alongside the shipped ones in /gallery-tracks.html so the
// best can be promoted into the cups. Candidates are NOT in TRACKS/CUPS: the phones'
// picker never sees them, and the display only builds one when ?track=<id> names it
// (main.js falls back to CANDIDATE_TRACKS for unknown ids in test mode).
//
// Seeded candidates bake through the SAME pipeline as shipped tracks (decoration +
// auto furniture); stunt candidates come from compose-stunt.mjs CANDIDATE_DESIGNS
// (closure + roll trims solved here, at bake time — their numbers live in the baked
// file, not in tracks.js, until one is promoted).
//
//   node scripts/gen-candidates.mjs
//
// Promote a winner: move its seed into gen-tracks.mjs SEEDS (or paste the composed
// segments into tracks.js like Coaster), register + re-bake, then drop it from here.
import fs from 'fs';
import path from 'path';
import { bakeSeed, buildTrack, placeFurniture, PROFILES } from './track-gen.mjs';
import { CANDIDATE_DESIGNS, compose } from './compose-stunt.mjs';
const ROOT = path.join(path.dirname(new URL(import.meta.url).pathname), '..');

// which {seed, profile} auditions in which cup section (shipped picks live in
// gen-tracks.mjs). The seeded cups' rosters were settled in the 2026-07-03 audition —
// currently only the Rooftop runs candidates (CANDIDATE_DESIGNS below).
const SEED_CANDIDATES = {};

const out = {};
for (const [cup, list] of Object.entries(SEED_CANDIDATES)) {
  for (const { seed, profile } of list) {
    const id = `cand-${profile}-${seed}`;
    const wp = bakeSeed(seed, profile);
    const t = buildTrack({ waypoints: wp });
    const furn = placeFurniture(t, { oils: PROFILES[profile].oilCount });
    out[id] = { name: `${profile[0].toUpperCase()}${profile.slice(1)} #${seed}`, cup, waypoints: wp, ...furn };
    console.log(`${id.padEnd(16)} len ${t.length.toFixed(0)} (~${(t.length * 0.124).toFixed(0)}s)  pillars ${t.pillars.length}  hills ${t.hills.length}  closed ${t.closed}`);
  }
}
for (const [name, make] of Object.entries(CANDIDATE_DESIGNS)) {
  const id = `cand-${name}`;
  const r = await compose(make());
  const t = buildTrack(r.segs);
  const furn = placeFurniture(t, { oils: 2 });
  out[id] = { name: name[0].toUpperCase() + name.slice(1), cup: 'rooftop', segments: r.segs, ...furn };
  console.log(`${id.padEnd(16)} len ${r.grade.len} (~${r.ai.lapSec}s)  strand ${r.grade.minStrand}  twist ${r.grade.twistRate}  seam ${r.grade.seamUp}  closed ${r.grade.closed}`);
  if (!r.grade.closed || r.grade.minStrand < 1.5 || r.grade.twistRate >= 0.21 || r.grade.seamUp < 0.9
    || (r.grade.sameLevelGap != null && r.grade.sameLevelGap < 0)) {
    console.log(`  ⚠ ${id} fails a structural gate — fix the design before auditioning it`);
    process.exitCode = 1;
  }
}

const body = Object.entries(out).map(([id, def]) => `  ${JSON.stringify(id)}: ${JSON.stringify(def)}`).join(',\n');
fs.writeFileSync(path.join(ROOT, 'public/shared/candidateTracks.js'),
  `// GENERATED by scripts/gen-candidates.mjs — DO NOT EDIT BY HAND.\n` +
  `// Audition candidates for /gallery-tracks.html (4 per cup section, alongside the\n` +
  `// shipped tracks). NOT part of TRACKS/CUPS: the picker never sees them; the display\n` +
  `// builds one only when ?track=<id> names it. Regenerate: node scripts/gen-candidates.mjs\n` +
  `export const CANDIDATE_TRACKS = {\n${body}\n};\n`);
console.log('wrote public/shared/candidateTracks.js');

// Controller Test Harness — drives a single phone screen in isolation for the
// gallery (/gallery-controller.html), with NO relay connection. main.js
// delegates here when the URL carries ?scenario=…; we apply the player's
// livery and lay out the requested screen from fake data.
//
// Pure DOM: the controller has no 3D scene, so nothing async to await.
import { buildCarPicker } from '../shared/carPicker.js';
import { buildModePicker } from '../shared/trackPicker.js';
import { TRACK_LIST } from '../shared/tracks.js';
import { TRACK_SCHEMATICS } from '../shared/trackSchematics.js';
import { packSchematic, unpackSchematic } from '../shared/schematicCodec.js';
import { applyLatencyChip, renderReadyFoot, motionHelpCopy } from './ui.js';
import { renderResultsBoard } from './resultsBoard.js';
import { setInputMode } from './driveSurface.js';

const FAKE_NAMES = ['Mia', 'Theo', 'Ava', 'Leo', 'Zoe', 'Max', 'Ivy', 'Sam'];

// Track catalog for the no-relay gallery preview. In a real game the controller
// renders whatever rides the room snapshot: pack/unpackSchematic(trackSchematic(geom))
// — an RDP-simplified, uint8-packed path, NOT the full-res map. The gallery has no
// relay/display, so we rebuild the list from the catalogue ids/names + the REAL
// precomputed schematics (shared/trackSchematics.js, generated by
// scripts/gen-track-schematics.js) — then ROUND-TRIP them through the exact same
// pack→unpack the wire uses, so the gallery shows precisely the fidelity a phone
// gets (corner detail + quantization), not a flattering full-res map. The
// controller stays Three-free (the schematic codec is pure math, no Three).
const PREVIEW_TRACKS = TRACK_LIST.map((t) => ({
  id: t.id, name: t.name, cup: t.cup, cupName: t.cupName, cupDifficulty: t.cupDifficulty,
  svg: unpackSchematic(packSchematic(TRACK_SCHEMATICS[t.id]))
}));

const el = (id) => document.getElementById(id);

// runControllerScenario({ scenario, color })
export function runControllerScenario(opts) {
  const COLORS = window.CAR_COLORS || ['#2bb673'];
  const scenario = opts.scenario;
  const color = Math.max(0, Math.min(opts.color || 0, COLORS.length - 1));

  const screens = { name: el('name'), lobby: el('lobby'), game: el('game'), results: el('results') };
  const show = (name) => { for (const k of Object.keys(screens)) screens[k].classList.toggle('hidden', k !== name); };

  // Apply the player's car livery (the --car custom property tints the HUD and
  // the car-picker tiles).
  const myColor = COLORS[color % COLORS.length];
  document.documentElement.style.setProperty('--car', myColor);

  window.__TEST__ = window.__TEST__ || {};

  // Car picker — the real shared layout (hero preview + stats + tap strip). Taps
  // re-render so the gallery shows the selection updating the big preview live.
  // The selection is remembered so the ready toggle (below) can re-render the
  // strip locked/unlocked without losing the picked car.
  let carSel = color;
  function renderCarPicker(selected = carSel, canPick = true) {
    carSel = selected;
    buildCarPicker({
      heroEl: el('car-hero'), stripEl: el('carpick'),
      selected: carSel, canPick, onPick: (i) => renderCarPicker(i, canPick)
    });
  }

  // The couch progression a preview lobby carries — the snapshot's `progress`
  // shape, synthesized mid-game: two starred cups, the Playroom still locked.
  // (gallery-controller-boards.spec pins the dressings only this shape can
  // produce, per the harness rule.)
  const PREVIEW_PROGRESS = {
    cups: [
      { id: 'beach', stars: 3, locked: false },
      { id: 'snow', stars: 2, locked: false },
      { id: 'backyard', stars: 1, locked: false },
      { id: 'canyon', stars: 0, locked: false },
      { id: 'rooftop', stars: 0, locked: true, unlockDone: 3, unlockNeed: 4 }
    ]
  };

  // Which lobby page this scenario shows — mirrors main.js renderLobbyPage.
  // The back chip is NOT set here: renderReadyFoot owns it, exactly as on the
  // live page, so a scenario can't show a corner the real phone wouldn't.
  function setLobbyPage(tab, isHost) {
    el('lobby').classList.toggle('lobby--race', isHost && tab === 'race');
  }
  // The chip has to actually step back, or the gallery is showing a dead
  // control — the same reason a locked car tile stops taking pointer events
  // instead of sitting there looking pressable.
  el('lobby-back').onclick = () => runControllerScenario({ scenario: 'lobby-host', color: color });

  // Mode picker — mirrors main.js renderModePicker: host only (non-host lobby
  // has no picker at all), on the RACE page. Taps re-render so the gallery
  // shows the pick move / the detail panel swap live, cursor included.
  function renderModePicker(selection, canPick, highlight = null) {
    if (!canPick) { el('trackpick').classList.add('hidden'); return; }
    el('trackpick').classList.remove('hidden');
    buildModePicker({
      stripEl: el('track-strip'), catalog: PREVIEW_TRACKS, progress: PREVIEW_PROGRESS,
      selection, highlight, canPick: true,
      onPickMode: (pick) => renderModePicker(pick, true),
      onHighlight: (rowId) => renderModePicker(selection, true, rowId)
    });
  }
  // The auto-picked default a host lobby opens with (mirrors maybeAutoSelectMode).
  const DEFAULT_MODE = { mode: 'cup', cupId: PREVIEW_TRACKS[0].cup };

  // Lobby footer — the SAME renderer as main.js (renderReadyFoot), fed fake
  // roster data. For a non-host, tapping toggles the ready state so the gallery
  // shows the held-down "Ready ✓" + waiting note live — and re-renders the car
  // picker locked while ready (mirrors main.js renderLobby); the host's "Start
  // race" button just renders (no race to start here).
  function renderReadyPreview(amHost, amReady, host, others, tab = 'car') {
    renderReadyFoot(el('ready-btn'), el('ready-note'),
      { amHost, amReady, tab, canStart: true, host, others, backEl: el('lobby-back') });
    if (!amHost) {
      renderCarPicker(carSel, !amReady);
      el('ready-btn').onclick = () => renderReadyPreview(amHost, !amReady, host, others, tab);
    }
  }

  // Results board — the LIVE renderer (resultsBoard.js), fed a synthesized
  // STANDINGS payload. The harness used to hand-roll its own twin of this markup,
  // and had already drifted from it: the race board never set #results-title, and
  // the cup board hardcoded "Race 2 of 4" instead of deriving it from the series.
  // A preview renders through the live renderer, never a copy of it.
  //
  // Every board is viewed as the HOST, so the host-only footer (the "New game" /
  // "Next race ▸" button) is what the gallery shows.
  // A row is FINISHED unless the scenario says otherwise: an unfinished row of
  // your own reads "Still racing" on the card, which a completed board must not
  // show. Only the "you crossed the line first" scenario opts rows out.
  //
  // `racePlace` defaults to the array position, which is right on any board still
  // in RACE order. A cup board is in CUP order, so its scenario states the race
  // placings itself — the card reports the RACE place, and defaulting them would
  // have the cup leader also winning every race.
  //
  // A FINISHED ROW ALWAYS CARRIES A TIME, because the model guarantees it and
  // both boards read it without checking. The cup scenarios used to set
  // `finished` and no `time`, which is a shape no real board produces — and the
  // moment the phone started showing a lap time it threw on the preview. The
  // default keeps the pairing whatever a scenario overrides.
  const ME = 1;   // this phone's peerIndex in the synthesized board; also the host
  const showBoard = (order, { over, series, settled }) => {
    show('results');
    renderResultsBoard(
      { over, series, settled, order: order.map((o, i) => {
        const row = { finished: true, racePlace: i + 1, ...o, playerId: o.me ? ME : 100 + i };
        // off racePlace, not the array index: a cup board is in CUP order, so
        // indexing here would hand the quickest lap to whoever leads the cup.
        if (row.finished && row.time == null) row.time = 28.4 + (row.racePlace - 1) * 2.3;
        return row;
      }) },
      { meId: ME, hostPeerIndex: ME, amHost: true, liveryOf: (i) => COLORS[i] || '#888' }
    );
  };

  // Latency chip preview — no relay here, so feed it a static reading.
  const setLatency = (halfMs, fastlane) => applyLatencyChip(el('latency'), halfMs, fastlane);

  const setSteer = (v) => { const f = el('steer-fill'); if (f) f.style.transform = `translateX(${v * 50}%)`; };
  function setHudName() {
    el('hud-name').textContent = FAKE_NAMES[color];     // who you are, top-left (mirrors the display)
  }
  // The item identity shows on the DISPLAY, not the phone — the only controller cue
  // is the ITEM button lighting up. Preview that by toggling its disabled state.
  function setUse(holding) { const a = el('action-btn'); if (a) a.disabled = !holding; }
  // mode: 'tilt' (default) | 'buttons' — through the LIVE setInputMode (main.js
  // booted the drive surface before delegating here), so the gallery previews
  // whatever the real mode switch does, not a copy of it. It doesn't persist —
  // that's main.js's applyInputMode, which a preview must never reach.
  function showDriveHud(mode = 'tilt') {
    show('game');
    setInputMode(mode);
    el('drive-hud').classList.remove('hidden');   // pause + settings ride inside it
    el('motion-tip').classList.add('hidden');     // no motion nag in a preview
  }

  switch (scenario) {
    case 'name':
      show('name');
      el('name-input').value = '';
      el('name-status').textContent = '';
      break;

    case 'name-connecting':
      show('name');
      el('name-input').value = FAKE_NAMES[color];
      el('name-input').disabled = true;
      el('name-form').querySelector('button').disabled = true;
      el('name-status').textContent = '';
      break;

    case 'lobby-host':
      // The host's CAR page: the picker waiting one step on, the stepper's
      // forward face saying "Select race", no back chip (nothing behind it).
      show('lobby');
      el('me-name').textContent = FAKE_NAMES[color];
      setLobbyPage('car', true);
      renderCarPicker(color); // default pick mirrors the livery slot
      renderModePicker(null, false); // the picker lives on the RACE page
      renderReadyPreview(true, false, null, [
        { name: FAKE_NAMES[(color + 1) % FAKE_NAMES.length], color: COLORS[(color + 1) % COLORS.length], ready: true },
        { name: FAKE_NAMES[(color + 2) % FAKE_NAMES.length], color: COLORS[(color + 2) % COLORS.length], ready: true }
      ], 'car');
      break;

    case 'lobby-race':
      // The host's RACE page: the pick grid with its stars, the auto-picked
      // first cup's detail open, everyone ready so Start is live — and the
      // corner's back chip, which is the only way home now the tabs are gone.
      show('lobby');
      el('me-name').textContent = FAKE_NAMES[color];
      setLobbyPage('race', true);
      renderModePicker(DEFAULT_MODE, true);
      renderReadyPreview(true, false, null, [
        { name: FAKE_NAMES[(color + 1) % FAKE_NAMES.length], color: COLORS[(color + 1) % COLORS.length], ready: true },
        { name: FAKE_NAMES[(color + 2) % FAKE_NAMES.length], color: COLORS[(color + 2) % COLORS.length], ready: true }
      ], 'race');
      break;

    case 'lobby-race-locked':
      // The locked Playroom examined: the detail panel is the unlock pitch
      // (rules + per-cup checks), the pick itself untouched.
      show('lobby');
      el('me-name').textContent = FAKE_NAMES[color];
      setLobbyPage('race', true);
      renderModePicker(DEFAULT_MODE, true, 'rooftop');
      renderReadyPreview(true, false, null, [
        { name: FAKE_NAMES[(color + 1) % FAKE_NAMES.length], color: COLORS[(color + 1) % COLORS.length], ready: true }
      ], 'race');
      break;

    case 'lobby-waiting':
      show('lobby');
      el('me-name').textContent = FAKE_NAMES[color];
      setLobbyPage('car', false);
      renderCarPicker(color);
      renderModePicker(null, false); // non-host: no picker (the big screen shows the pick)
      // Already readied up and so is everyone else, so the note shows the
      // tinted-name "Waiting for <HOST> to start…" treatment.
      renderReadyPreview(false, true,
        { name: FAKE_NAMES[(color + 1) % FAKE_NAMES.length], color: COLORS[(color + 1) % COLORS.length] },
        [{ name: FAKE_NAMES[(color + 2) % FAKE_NAMES.length], color: COLORS[(color + 2) % COLORS.length], ready: true }]);
      break;

    case 'settings':
    case 'settings-buttons': {
      // Settings popup over the lobby, for the gallery — both faces: the tilt
      // demo (default) and the buttons demo ('settings-buttons'). modals.js owns
      // the live open/close (and its auto-show is suppressed in scenario mode),
      // so here we just lay out the host lobby and pop the overlay open with the
      // card flipped to the right mode (mirrors refreshSettingsCard). Motion
      // recovery is its own scenario below.
      show('lobby');
      el('me-name').textContent = FAKE_NAMES[color];
      // both mode cards' demo phones show the player's name (mirrors openSettings)
      for (const n of document.querySelectorAll('.phone-name')) n.textContent = FAKE_NAMES[color];
      setLobbyPage('car', true);
      renderCarPicker(color);
      renderModePicker(null, false);   // the host's CAR page sits behind the popup
      renderReadyPreview(true, false, null, [
        { name: FAKE_NAMES[(color + 1) % FAKE_NAMES.length], color: COLORS[(color + 1) % COLORS.length], ready: true }
      ], 'car');
      const buttons = scenario === 'settings-buttons';
      el('settings-card').classList.toggle('is-buttons', buttons);
      el('input-tilt').setAttribute('aria-checked', String(!buttons));
      el('input-buttons').setAttribute('aria-checked', String(buttons));
      // This is the HOST's card, so the TV section shows with Sound on
      // (mirrors refreshSettingsCard's host branch).
      el('tv-seg').classList.remove('hidden');
      el('sound-toggle').setAttribute('aria-checked', 'true');
      el('settings-overlay').classList.remove('hidden');
      el('settings-done').focus();   // seed focus inside the dialog (mirrors openSettings)
      break;
    }

    case 'motion-blocked': {
      // The separate motion-blocked alert over the lobby. Preview the richest
      // 'denied' branch (title + status + Allow button + Settings fix), pulling the
      // SAME copy main.js renders (motionHelpCopy in ui.js) so the gallery can't
      // drift from the live text.
      show('lobby');
      el('me-name').textContent = FAKE_NAMES[color];
      setLobbyPage('car', true);
      renderCarPicker(color);
      renderModePicker(null, false);   // the host's CAR page sits behind the popup
      renderReadyPreview(true, false, null, [
        { name: FAKE_NAMES[(color + 1) % FAKE_NAMES.length], color: COLORS[(color + 1) % COLORS.length], ready: true }
      ], 'car');
      const copy = motionHelpCopy('denied');
      el('motion-title').textContent = copy.title;
      el('motion-status').textContent = copy.status;
      el('motion-allow').classList.toggle('hidden', !copy.allow);
      const fix = el('motion-fix');
      fix.classList.toggle('hidden', !copy.fix);
      if (copy.fix) fix.innerHTML = copy.fix;
      el('motion-overlay').classList.remove('hidden');
      el('motion-done').focus();
      break;
    }

    case 'lobby-joining':
      // Late joiner: scanned the QR while a race was running. The lobby with the
      // car picker live but no ready button — just the "race in progress" note
      // (mirrors main.js renderLobby's waitingForNextRace branch).
      show('lobby');
      el('me-name').textContent = FAKE_NAMES[color];
      setLobbyPage('car', false);   // mid-race joiner: no tabs, no race page
      renderCarPicker(color);
      renderModePicker(null, false);
      el('ready-btn').classList.add('hidden');
      el('ready-note').textContent = 'You’re in the next race!'; // keep in sync with main.js renderLobby
      break;

    case 'countdown':
      // No countdown on the controller — the full HUD is up from the first beat
      // (the 3..2..1..GO lives on the display). Same as 'playing' but pre-fastlane.
      showDriveHud();
      setSteer(0);
      setHudName();
      setUse(false);           // USE off (empty slot)
      setLatency(24, false);   // pre-fastlane: WS reading, no bolt
      break;

    case 'playing':
      showDriveHud();
      setSteer(0.4); // mid-right tilt, so the steer bar reads off-center
      setHudName();
      setUse(true);            // USE lit (holding an item; identity is on the display)
      setLatency(16, true);    // fastlane up: low RTT + bolt
      break;

    case 'playing-buttons':
      // The button-steering face of the drive HUD: ‹ / ITEM / › in a row, the
      // left button held (steer bar hard left mirrors it — binary, so full lock).
      showDriveHud('buttons');
      setSteer(-1);
      el('steer-left').classList.add('held');
      setHudName();
      setUse(true);
      setLatency(16, true);
      break;

    case 'finished':
      // Your car crossed the line — the phone flips to the results board with your
      // finished row while the rest of the 8-car field is still out (not the
      // drive HUD).
      setLatency(19, true);
      showBoard([
        { name: FAKE_NAMES[color], colorIndex: color, time: 31.2, me: true, finished: true },
        ...[1, 2, 3, 4, 5, 6, 7].map((i) => ({
          name: i === 2 ? 'Bolt' : FAKE_NAMES[(color + i) % FAKE_NAMES.length],
          colorIndex: (color + i) % COLORS.length, ai: i >= 2, finished: false
        }))
      ], { over: false });
      break;

    case 'paused':
      showDriveHud();
      setSteer(0.2);
      setHudName();
      setUse(true);            // USE lit
      setLatency(18, true);
      el('pause-btn').disabled = true;     // shown by showDriveHud; overlay covers it while paused
      el('pause-overlay').classList.remove('hidden');
      break;

    case 'results':
      // Final board (race over) on the full 8-car field, viewed as the host so
      // the "New game" button shows. The last row is a late joiner waiting on
      // the next race.
      setLatency(20, true);
      showBoard([
        { name: FAKE_NAMES[(color + 1) % FAKE_NAMES.length], colorIndex: (color + 1) % COLORS.length, time: 28.4, finished: true },
        { name: FAKE_NAMES[color],                           colorIndex: color,                       time: 31.2, me: true, finished: true },
        { name: 'Bolt',                                      colorIndex: (color + 2) % COLORS.length, time: 33.9, ai: true, finished: true },
        { name: FAKE_NAMES[(color + 3) % FAKE_NAMES.length], colorIndex: (color + 3) % COLORS.length, time: 36.5, finished: true },
        ...[4, 5, 6, 7].map((i) => ({
          name: FAKE_NAMES[(color + i) % FAKE_NAMES.length],
          colorIndex: (color + i) % COLORS.length, ai: true, time: 36.5 + i, finished: true
        })),
        { name: 'Pip', colorIndex: (color + 4) % COLORS.length, joining: true }
      ], { over: true });
      break;

    case 'intermission':
      // Mid-cup standings between two series races, viewed as the host: points
      // board in cup order (the +6 row leads on total despite this race's +9)
      // and the host's "Next race ▸".
      setLatency(20, true);
      showBoard([
        { name: FAKE_NAMES[(color + 1) % FAKE_NAMES.length], colorIndex: (color + 1) % COLORS.length, gained: 6, points: 21, racePlace: 2 },
        { name: FAKE_NAMES[color],                           colorIndex: color,                       gained: 9, points: 19, me: true, racePlace: 1 },
        { name: 'Bolt',                                      colorIndex: (color + 2) % COLORS.length, gained: 3, points: 9, ai: true, racePlace: 3 },
        { name: FAKE_NAMES[(color + 3) % FAKE_NAMES.length], colorIndex: (color + 3) % COLORS.length, gained: 0, points: 3, racePlace: 5 },
        ...[4, 5, 6, 7].map((i) => ({
          name: FAKE_NAMES[(color + i) % FAKE_NAMES.length],
          colorIndex: (color + i) % COLORS.length, ai: true,
          // cup order is sorted by TOTAL — the tail must not out-point row 4's 3 pts
          gained: i === 4 ? 1 : 0, points: [3, 2, 1, 0][i - 4],
          racePlace: i === 4 ? 4 : i + 2
        }))
      ], { over: true, series: { final: false, raceIndex: 1, raceCount: 4, cupName: PREVIEW_TRACKS[0].cupName } });
      break;

    case 'cup-podium':
    case 'cup-podium-settled': {
      // The cup's last board, in its two states. Before the TV has revealed the
      // cup this screen is still about the RACE; `settled` is the display's cue
      // that the reveal has landed and it can report the cup instead.
      //
      // The two disagree ON PURPOSE here: I came 3rd in the last race and still
      // took the cup. A card wired to the wrong one, or a title that did not
      // move with it, would read perfectly plausibly on a preview where they
      // happened to match.
      setLatency(20, true);
      showBoard([
        { name: FAKE_NAMES[color],                           colorIndex: color,                       gained: 3, points: 36, me: true, racePlace: 3 },
        { name: FAKE_NAMES[(color + 1) % FAKE_NAMES.length], colorIndex: (color + 1) % COLORS.length, gained: 9, points: 24, racePlace: 1 },
        { name: 'Bolt',                                      colorIndex: (color + 2) % COLORS.length, gained: 6, points: 12, ai: true, racePlace: 2 },
        { name: FAKE_NAMES[(color + 3) % FAKE_NAMES.length], colorIndex: (color + 3) % COLORS.length, gained: 1, points: 4, racePlace: 4 },
        ...[4, 5, 6, 7].map((i) => ({
          name: FAKE_NAMES[(color + i) % FAKE_NAMES.length],
          colorIndex: (color + i) % COLORS.length, ai: true, gained: 0, points: 8 - i, racePlace: i + 1
        }))
      ], {
        over: true, settled: scenario === 'cup-podium-settled',
        series: { final: true, raceIndex: 3, raceCount: 4, cupName: PREVIEW_TRACKS[0].cupName }
      });
      break;
    }

    case 'conn-lost':
    case 'conn-screen-gone':
    case 'conn-replaced': {
      // Connection overlay terminal states (copy mirrors main.js's onStatus
      // handlers), previewed over the drive HUD — the mid-race drop is the
      // case the overlay exists for. All three show the "Exit to start"
      // escape hatch; only 'lost' also offers a manual retry.
      showDriveHud();
      setSteer(0);
      setHudName();
      const [title, msg, retry] = {
        'conn-lost': ['Connection lost', 'Scan the QR on the big screen to take your seat back — or try again here.', true],
        'conn-screen-gone': ['Waiting for the big screen…', 'The host’s screen dropped — hang tight, it’ll reconnect you.', false],
        'conn-replaced': ['Opened on another tab', 'This seat is now controlled from another tab or device.', false]
      }[scenario];
      el('conn-title').textContent = title;
      el('conn-msg').textContent = msg;
      el('conn-retry').classList.toggle('hidden', !retry);
      el('conn-leave').classList.remove('hidden');
      el('conn').classList.remove('hidden');
      break;
    }

    default:
      console.warn('[ControllerTestHarness] unknown scenario:', scenario);
  }
}

// Bake the gallery's scenario table into Swift, for the screenshot runner.
//
//   node shells/tvos/scripts/gen-scenarios.mjs      (called by stage-assets.sh)
//
// WHY CODEGEN AND NOT AN ENVIRONMENT VARIABLE. The obvious design is for the
// capture script to hand the runner a list — and `xcodebuild` does document
// `TEST_RUNNER_FOO=bar` as the way to put `FOO` in a test process's environment.
// It does not arrive: a device run of this project reaches
// `ProcessInfo.processInfo.environment` with no TTP key under either spelling,
// prefixed or stripped. Rather than keep guessing at that plumbing, the table is
// compiled in.
//
// ONE TEST METHOD PER SCENARIO, which is the part that earns the codegen. The
// runner used to be a single test looping the list, so the device shot all
// eighteen boards however few you asked for and `--only` could only throw the
// extras away after export — changing one lobby detail cost a full-table
// capture. `xcodebuild -only-testing:` selects a METHOD, and it is the one
// selector that does survive the trip to a device, so a method per scenario is
// what makes `--only` mean something on the far side.
//
// STILL SINGLE-SOURCED: this reads `public/shared/galleryScenarios.js`, the same
// module the live web gallery, the web capture and `tests/shots-manifest.test.js`
// read. The output is BUILD OUTPUT, not a committed bake: `Generated/` is
// gitignored, and `stage-assets.sh` reruns this unconditionally on every staging,
// so the Swift can never be fresher or staler than the last stage — there is no
// committed copy to gate.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import { GALLERY_SCENARIOS } from '../../../public/shared/galleryScenarios.js';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(HERE, '..', 'Generated', 'ShotScenarios.swift');

/// The scenario id a `-only-testing:` selector needs, as an XCTest method name.
///
/// EXPORTED BECAUSE TWO SIDES SPELL IT: this generator writes the methods and
/// `scripts/capture-shots-tvos.mjs` names them on the xcodebuild command line. A
/// second hand-written copy of the rule would drift on the first scenario id
/// that contains something Swift will not take, and the symptom would be
/// xcodebuild refusing a selector for a test that is right there.
///
/// Hyphens are the only thing in the shipped ids that a Swift identifier
/// rejects; anything else is caught by the sweep below rather than silently
/// mangled.
export function shotTestMethod(id) {
  return `testShot_${id.replace(/-/g, '_')}`;
}

export function generate() {
  const bad = GALLERY_SCENARIOS.filter((s) => !/^[a-z0-9-]+$/.test(s.id));
  if (bad.length) {
    throw new Error(
      `scenario ids must be [a-z0-9-] to become Swift method names: ${bad.map((s) => s.id).join(', ')}`);
  }

  const methods = GALLERY_SCENARIOS
    .map((s) => `    func ${shotTestMethod(s.id)}() { capture("${s.id}") }`)
    .join('\n');

  const source = `// GENERATED by shells/tvos/scripts/gen-scenarios.mjs — do not edit.
//
// The gallery's scenario ids, from public/shared/galleryScenarios.js. Compiled
// into the screenshot runner rather than passed as an environment variable,
// because a device run never receives one (see the generator's header).
//
// ${GALLERY_SCENARIOS.length} screens, ONE TEST EACH so that
// \`xcodebuild -only-testing:TinyTrackPartyShots/ShotTests/<method>\` can shoot a
// single board. The bodies are all \`ShotTests.capture\`; nothing but the id
// differs, and the id is the only thing the runner needs.
//
// There is no list constant here on purpose. The METHODS are the table now —
// XCTest enumerates them, and a second copy as an array would be a thing that
// could disagree with them.

extension ShotTests {
${methods}
}
`;

  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, source);
  return GALLERY_SCENARIOS.length;
}

// Only when RUN, never when imported — `capture-shots-tvos.mjs` imports
// `shotTestMethod` from here and must not rewrite the bake as a side effect of
// asking what a method is called.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const n = generate();
  console.log(`==> ${n} scenarios -> Generated/ShotScenarios.swift`);
}
